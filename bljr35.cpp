// pernyataan while
#include <iostream>
using namespace std;
int main() {
    int i; //sebagai variabel pencacah yg menyatakan
           //jumlah perulangan tulisan Nilai i
    i = 0; //di isi dg 0
    while (i < 10) {
        cout << "Nilai i "  << endl;
        i++; //menambah nilai i sebanyak 1 setiap perulangan
    }
}